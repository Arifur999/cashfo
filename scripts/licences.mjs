// Writes src/lib/customer/licences.ts: each package the app ships (package.json
// "dependencies") with its licence, for Settings › Resources & legal ›
// Open-source licences. Run it after adding or removing a dependency:
//   node scripts/licences.mjs
// licences.test.ts fails until the list matches package.json again.
import { readFileSync, writeFileSync } from "node:fs";

const read = (file) => JSON.parse(readFileSync(file, "utf8"));
const { dependencies } = read("package.json");
const rows = Object.keys(dependencies)
  .sort()
  .map((name) => {
    const info = read(`node_modules/${name}/package.json`);
    const licence = typeof info.license === "string" ? info.license : (info.license?.type ?? "See the package");
    return `  { name: ${JSON.stringify(name)}, licence: ${JSON.stringify(licence)} },`;
  });
const body = `// Generated by scripts/licences.mjs from package.json; don't edit by hand.
export interface OpenSourcePackage {
  name: string;
  licence: string;
}

export const OPEN_SOURCE_PACKAGES: OpenSourcePackage[] = [
${rows.join("\n")}
];
`;
writeFileSync("src/lib/customer/licences.ts", body);
console.log(`wrote ${rows.length} packages`);
