export type CategoryIconName = keyof typeof CATEGORY_ICONS;

export const CATEGORY_ICON_NAMES = Object.keys(CATEGORY_ICONS) as CategoryIconName[];

export const getCategoryIcon = (name: string | null | undefined): LucideIcon | null =>
  name && Object.hasOwn(CATEGORY_ICONS, name) ? CATEGORY_ICONS[name as CategoryIconName] : null;
